import AppKit
import Foundation

/// While a session is active, sends the Mac's clipboard text to the agent when it changes,
/// and applies text arriving from the remote side (CLIPBOARD_SET) without echoing it back.
@MainActor
final class ClipboardSync {
    static let maxBytes = 1 << 20

    private let pasteboard = NSPasteboard.general
    private let send: (String) -> Void
    private var lastChangeCount: Int
    private var ownChangeCount = -1
    private var task: Task<Void, Never>?

    /// Password managers mark secrets with these types (nspasteboard.org); never send them.
    private static let skippedTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    init(send: @escaping (String) -> Void) {
        self.send = send
        self.lastChangeCount = NSPasteboard.general.changeCount
    }

    var isRunning: Bool { task != nil }

    func start() {
        guard task == nil else { return }
        lastChangeCount = pasteboard.changeCount
        task = Task { @MainActor [weak self] in
            while !Task.isCancelled {
                try? await Task.sleep(nanoseconds: 500_000_000)
                guard let self else { return }
                self.poll()
            }
        }
    }

    func stop() {
        task?.cancel()
        task = nil
    }

    func setFromRemote(_ text: String) {
        guard text.utf8.count <= ClipboardSync.maxBytes else { return }
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        ownChangeCount = pasteboard.changeCount
        lastChangeCount = ownChangeCount
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard count != ownChangeCount else { return }
        let types = pasteboard.types ?? []
        if types.contains(where: { ClipboardSync.skippedTypes.contains($0) }) { return }
        guard let text = pasteboard.string(forType: .string), !text.isEmpty,
              text.utf8.count <= ClipboardSync.maxBytes else { return }
        send(text)
    }
}
