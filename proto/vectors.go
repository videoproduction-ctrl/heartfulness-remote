package proto

import (
	"crypto/ed25519"
	"encoding/hex"
)

// VectorSet is the JSON shape of testdata/vectors.json.
type VectorSet struct {
	Note        string            `json:"note"`
	HostSeed    string            `json:"hostSeedHex"`
	HostPub     string            `json:"hostPub"`
	DeviceSeed  string            `json:"deviceSeedHex"`
	DevicePub   string            `json:"devicePub"`
	Fingerprint string            `json:"hostFingerprint"`
	TBS         []TBSVector       `json:"tbs"`
	Commit      string            `json:"pairCommit"`
	SAS         string            `json:"sas"`
	Setup       SetupVector       `json:"setup"`
	Cert        Cert              `json:"cert"`
	Join        JoinVector        `json:"join"`
	Inputs      map[string]string `json:"inputs"`
}

// TBSVector is one transcript with its Ed25519 signature (Ed25519 is deterministic).
type TBSVector struct {
	Label  string   `json:"label"`
	Fields []string `json:"fieldsB64"`
	TBSHex string   `json:"tbsHex"`
	Signer string   `json:"signer"`
	Sig    string   `json:"sig"`
}

// JoinVector covers adding another Mac (PROTOCOL.md §10).
type JoinVector struct {
	MacID       string `json:"macId"`
	T           string `json:"t"`
	Code        string `json:"code"`
	Kc          string `json:"kc"`
	Ka          string `json:"ka"`
	ClaimCommit string `json:"claimCommit"`
	SetupMAC    string `json:"setupMac"`
	HostMAC     string `json:"hostMac"`
}

// SetupVector covers the bootstrap derivations.
type SetupVector struct {
	T           string `json:"t"`
	Kc          string `json:"kc"`
	Ka          string `json:"ka"`
	ClaimCommit string `json:"claimCommit"`
	Name        string `json:"name"`
	Kind        string `json:"kind"`
	SetupMAC    string `json:"setupMac"`
}

func seq(start byte, n int) []byte {
	b := make([]byte, n)
	for i := range b {
		b[i] = start + byte(i)
	}
	return b
}

// Vectors builds the deterministic vector set.
func Vectors() VectorSet {
	hostSeed := seq(0x01, 32)
	devSeed := seq(0x41, 32)
	host := ed25519.NewKeyFromSeed(hostSeed)
	dev := ed25519.NewKeyFromSeed(devSeed)
	hostPub := []byte(host.Public().(ed25519.PublicKey))
	devPub := []byte(dev.Public().(ed25519.PublicKey))

	nd := seq(0x80, 32)
	na := seq(0xa0, 32)
	reqID := seq(0x10, 16)
	sessID := seq(0x20, 16)
	cn := seq(0x30, 32)
	hn := seq(0x50, 32)
	nonce := seq(0x60, 32)
	origin := "https://remote.example.test"
	offer := "v=0\r\no=- 1 2 IN IP4 127.0.0.1\r\na=fingerprint:sha-256 AA:BB\r\n"
	answer := "v=0\r\no=- 3 4 IN IP4 127.0.0.1\r\na=fingerprint:sha-256 CC:DD\r\n"
	commit := PairCommit(devPub, nd)

	type spec struct {
		label  string
		signer string
		fields [][]byte
	}
	specs := []spec{
		{LabelHostAuth, "host", [][]byte{Str(origin), nonce}},
		{LabelClientAuth, "device", [][]byte{Str(origin), nonce}},
		{LabelPairChallenge, "host", [][]byte{reqID, commit, na, hostPub}},
		{LabelPairApprove, "device", [][]byte{reqID, hostPub, devPub, nd, na, Str("Chrome on Windows"), Str("browser")}},
		{LabelRevokeRequest, "device", [][]byte{hostPub, devPub, Int(1760000000)}},
		{LabelKillRequest, "device", [][]byte{hostPub, Str("kill"), Int(1760000000)}},
		{LabelOffer, "device", [][]byte{sessID, hostPub, devPub, cn, hn, Hash([]byte(offer))}},
		{LabelAnswer, "host", [][]byte{sessID, hostPub, devPub, cn, hn, Hash([]byte(offer)), Hash([]byte(answer))}},
	}
	var tv []TBSVector
	for _, s := range specs {
		key := host
		if s.signer == "device" {
			key = dev
		}
		var fs []string
		for _, f := range s.fields {
			fs = append(fs, B64(f))
		}
		tbs := TBS(s.label, s.fields...)
		tv = append(tv, TBSVector{
			Label: s.label, Fields: fs, TBSHex: hex.EncodeToString(tbs),
			Signer: s.signer, Sig: B64(ed25519.Sign(key, tbs)),
		})
	}

	t := seq(0xc0, 32)
	kc, ka, err := SetupKeys(t)
	if err != nil {
		panic(err)
	}
	jt := seq(0xe0, JoinSecretSize)
	jkc, jka, err := SetupKeys(jt)
	if err != nil {
		panic(err)
	}
	cert := SignCert(host, Cert{HostPub: B64(hostPub), DevicePub: B64(devPub), Name: "Phone ✓", Kind: "browser", IssuedAt: 1760000000})

	return VectorSet{
		Note:        "Generated by `go run ./proto/cmd/genvectors`. Do not edit by hand.",
		HostSeed:    hex.EncodeToString(hostSeed),
		HostPub:     B64(hostPub),
		DeviceSeed:  hex.EncodeToString(devSeed),
		DevicePub:   B64(devPub),
		Fingerprint: Fingerprint(hostPub),
		TBS:         tv,
		Commit:      B64(commit),
		SAS:         SAS(hostPub, devPub, nd, na),
		Setup: SetupVector{
			T: B64(t), Kc: B64(kc), Ka: B64(ka), ClaimCommit: B64(ClaimCommit(kc)),
			Name: "Phone ✓", Kind: "browser",
			SetupMAC: B64(SetupMAC(ka, hostPub, devPub, "Phone ✓", "browser")),
		},
		Cert: cert,
		Join: JoinVector{
			MacID: MacID(hostPub), T: B64(jt), Code: JoinCode(jt), Kc: B64(jkc), Ka: B64(jka),
			ClaimCommit: B64(ClaimCommit(jkc)),
			SetupMAC:    B64(SetupMAC(jka, hostPub, devPub, "Phone ✓", "browser")),
			HostMAC:     B64(HostConfirmMAC(jka, hostPub, devPub)),
		},
		Inputs: map[string]string{
			"nd": B64(nd), "na": B64(na), "requestId": B64(reqID), "sessionId": B64(sessID),
			"clientNonce": B64(cn), "hostNonce": B64(hn), "nonce": B64(nonce), "origin": origin,
			"offerSdp": offer, "answerSdp": answer,
		},
	}
}
